function a(
  id: string,
  category: AnomalyContributor['category'],
  title: string,
  severity: AnomalyContributor['severity'],
  explanation: string,
  metricLabel: string,
  metricValue: string,
  normalRange: string,
  detail?: string,
): AnomalyContributor {
  return { id, category, title, severity, explanation, metricLabel, metricValue, normalRange, detail }
}

const mismatch = (id: string, fin: number, phy: number): AnomalyContributor =>
  a(
    `${id}-mm`,
    'progress_mismatch',
    'Progress mismatch',
    fin - phy >= 35 ? 'high' : 'medium',
    'Financial progress is substantially ahead of reported physical progress.',
    'Financial vs physical',
    `${fin}% / ${phy}%`,
    'Gap typically within 10–15 percentage points',
    'Peer works of similar type report physical progress within 12 points of expenditure booking.',
  )

const financial = (id: string, exp: string, peer: string): AnomalyContributor =>
  a(
    `${id}-fin`,
    'financial',
    'Financial anomaly',
    'high',
    'Expenditure is significantly higher than comparable projects of similar type and scale.',
    'Booked expenditure',
    exp,
    peer,
  )

const timeline = (id: string, actual: number, expected: number): AnomalyContributor =>
  a(
    `${id}-tl`,
    'timeline',
    'Timeline anomaly',
    actual - expected >= 6 ? 'high' : 'medium',
    'Project duration is above the historical range for comparable projects.',
    'Duration',
    `${actual} months`,
    `${expected - 2}–${expected + 1} months`,
  )

const vendor = (id: string): AnomalyContributor =>
  a(
    `${id}-vn`,
    'vendor',
    'Vendor pattern',
    'medium',
    'Contractor concentration pattern differs from comparable projects.',
    'Share of district works',
    '38% with same agency',
    'Typical concentration below 18%',
  )

